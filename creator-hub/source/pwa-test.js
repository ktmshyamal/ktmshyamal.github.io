const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch(); const ctx = await b.newContext({ acceptDownloads: true, viewport: { width: 390, height: 800 } }); const pg = await ctx.newPage();
  const errs = []; pg.on('pageerror', e => errs.push(e.message));
  await pg.route('**/*', r => /localhost/.test(r.request().url()) ? r.continue() : r.abort());
  await pg.goto('http://localhost:8765/index.html'); await pg.waitForTimeout(1500);
  console.log('sw', await pg.evaluate(async () => !!(await navigator.serviceWorker.getRegistration())));
  console.log('manifest', await pg.evaluate(() => fetch('manifest.webmanifest').then(r => r.json()).then(j => j.name)));
  console.log('note', await pg.textContent('#syncNote'));
  await pg.evaluate(() => { state.settings.brand = 'ZZ Test'; save(); }); await pg.waitForTimeout(500);
  await pg.click('#tab-settings');
  const [dl] = await Promise.all([pg.waitForEvent('download'), pg.click('[data-act=backup]')]);
  const path = await dl.path(); console.log('backup file', dl.suggestedFilename());
  await pg.evaluate(() => { state.settings.brand = 'Changed'; save(); }); 
  pg.on('dialog', d => d.accept());
  await pg.setInputFiles('#restoreFile', path); await pg.waitForTimeout(500);
  console.log('restored brand', await pg.evaluate(() => state.settings.brand));
  await pg.reload(); await pg.waitForTimeout(1200);
  console.log('after reload brand', await pg.evaluate(() => state.settings.brand));
  console.log('errors', JSON.stringify(errs)); await b.close();
})();
